const CACHE_NAME = "mishiro-pwa-v9";
const APP_SHELL = [
  "./",
  "./index.html",
  "./tailwind.css?v=9",
  "./styles.css?v=9",
  "./app.js?v=9",
  "./manifest.webmanifest",
  "./icons/mishiro-192.png",
  "./icons/mishiro-512.png",
  "./assets/pez-dorado.svg",
  "./assets/checkpoint.png",
  "./assets/mishiro-personaje.png",
  "./assets/bioma-nivel-1.png",
  "./assets/bioma-nivel-2.png",
  "./assets/bioma-nivel-3.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;

  if (event.request.mode === "navigate") {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put("./index.html", copy));
          return response;
        })
        .catch(() => caches.match("./index.html"))
    );
    return;
  }

  if (event.request.destination === "style" || event.request.destination === "script") {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          return response;
        })
        .catch(() => caches.match(event.request))
    );
    return;
  }

  event.respondWith(
    caches.match(event.request).then((cached) => cached || fetch(event.request).then((response) => {
      const copy = response.clone();
      caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
      return response;
    }))
  );
});
